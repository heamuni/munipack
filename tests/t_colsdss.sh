C="--photsys-ref Gunn -f g --col-ra RAJ2000 --col-dec DEJ2000 -c cat.fits \
    --col-mag rpmag --col-magerr e_rpmag"
slope() {   # the slope of MAG - r against g - r
    match "cat.fits[1]" "RAJ2000 DEJ2000 gpmag rpmag" \
        "$1[PHOTOMETRY]" "RAJ2000 DEJ2000 MAG" 3e-4 \
        | awk '$3 < 99 { print $3 - $2, $1 - $2 }' > res.txt
    awk '{ x = $2; y = $1; n++; sx += x; sy += y; sxx += x * x; sxy += x * y }
        END { print (n * sxy - sx * sy) / (n * sxx - sx * sx) }' res.txt
}

# The frame is rendered from the catalogue, so its colours are exact and
# (by the man page) the error columns should be left out; they are kept
# here as in the previous version: the SDSS errors of g - r are 1-2% of its
# range (lambda 0.99), the correction for them (BUGS P57) moves k1 by
# 0.002, well within the checks
mkdir o1 o2 nc
munipack phcal $C --color-term gpmag,rpmag,e_gpmag,e_rpmag -t o1 g.fits \
    > /dev/null 2>&1
k=$(key "o1/g.fits[PHOTOMETRY]" COLTK1)
ke=$(key "o1/g.fits[PHOTOMETRY]" COLTK1E)
check "COLTK1 (-1)" "$k" -1.02 -0.98
check "COLTK1E" "$ke" 0.001 0.01
check "(COLTK1 + 1) / COLTK1E" "$(awk -v k="$k" -v e="$ke" 'BEGIN { print (k + 1) / e }')" -3 3
s=$(slope o1/g.fits)
check "stars" "$(wc -l < res.txt)" 85 93
check "colour slope [mag/mag]" "$s" -0.015 0.015
read -r med sd n <<< "$(cut -d' ' -f1 res.txt | stats)"
check "MAG - r: robust sd" "$sd" 0 0.015
check "PHSYSERR" "$(key "o1/g.fits[PHOTOMETRY]" PHSYSERR)" 0 0.01

munipack phcal $C --color-term gpmag,rpmag,e_gpmag,e_rpmag --color-order 2 \
    -t o2 g.fits > /dev/null 2>&1
check "order 2: COLTK1 (-1)" "$(key "o2/g.fits[PHOTOMETRY]" COLTK1)" -1.02 -0.98
check "order 2: COLTK2 (0)" "$(key "o2/g.fits[PHOTOMETRY]" COLTK2)" -0.02 0.02

# without the colour term: the slope of the colours, a systematic error
